"""A read-only queries seam over bundled synthetic data, for the public demo.

``FixtureQueries`` has the same read methods as ``app.queries.Queries`` and serves
them from ``reforge/demo/fixtures.json`` (generated by ``scripts/make_demo_data.py``;
every reel, beat, frame and caption in it is synthetic). Every write method raises
``PermissionError``: the demo's ``DEMO_READ_ONLY`` middleware refuses writes before
any route runs, and this seam refuses them again if that ever regressed.
"""
from __future__ import annotations

import copy
import json
from datetime import datetime
from pathlib import Path
from typing import Any

from reforge.app.queries import effective_in_point

DEMO_DIR = Path(__file__).resolve().parent.parent / "demo"
FIXTURES_PATH = DEMO_DIR / "fixtures.json"


def _dt(value: str | None) -> datetime | None:
    return datetime.fromisoformat(value) if value else None


class FixtureQueries:
    """Serve the review app from synthetic fixtures; refuse every write."""

    def __init__(self, path: Path | str = FIXTURES_PATH) -> None:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        self._reels: dict[int, dict] = {r["id"]: r for r in data["reels"]}
        self._slots: dict[int, dict] = {}
        for reel in data["reels"]:
            for s in reel["slots"]:
                s = dict(s, reel_id=reel["id"])
                s["effective_in"] = effective_in_point(
                    s.get("params"), s.get("candidates"), s.get("swapped_moment_id"),
                    s.get("moment_start") or 0.0, s.get("moment_end") or 0.0)
                self._slots[s["id"]] = s
        self._runs: list[dict] = data["runs"]
        self._moments: list[dict] = data["moments"]
        self._scheduled: dict[int, dict] = {int(k): v for k, v in data["scheduled"].items()}
        self._references: list[str] = data["references"]

    # -- health ---------------------------------------------------------------

    def ping(self) -> bool:
        return True

    # -- reads ----------------------------------------------------------------

    def _reel_slots(self, reel_id: int) -> list[dict]:
        return sorted((s for s in self._slots.values() if s["reel_id"] == reel_id),
                      key=lambda s: s["idx"])

    def _first_thumb(self, reel_id: int) -> str | None:
        return next((s["thumbnail_key"] for s in self._reel_slots(reel_id)
                     if s.get("thumbnail_key")), None)

    def _pending(self, reel_id: int) -> bool:
        sched = self._scheduled.get(reel_id)
        return sched is not None and sched["status"] in ("scheduled", "publishing")

    def list_reels(self, limit: int = 200) -> list[dict[str, Any]]:
        out = []
        for r in sorted(self._reels.values(), key=lambda r: r["id"], reverse=True)[:limit]:
            slots = self._reel_slots(r["id"])
            out.append({"id": r["id"], "ref": r["ref"], "created": r["created"],
                        "approved": r["approved"], "grade": r.get("grade"),
                        "slot_count": len(slots),
                        "reviewed_count": sum(1 for s in slots if s.get("human_verdict")),
                        "thumbnail_key": self._first_thumb(r["id"]),
                        "published": r.get("published", False), "posted": r.get("posted", ""),
                        "is_trial": r.get("is_trial", False),
                        "pending_post": self._pending(r["id"])})
        return out

    def reel_detail(self, reel_id: int) -> dict[str, Any] | None:
        r = self._reels.get(reel_id)
        if r is None:
            return None
        reel = {k: r.get(k) for k in ("id", "ref", "created", "approved", "output_key",
                                      "grade", "caption", "posted")}
        reel.update(cut_dirty=r.get("cut_dirty", False), published=r.get("published", False),
                    is_trial=r.get("is_trial", False), playable=bool(r.get("output_key")))
        return {"reel": reel, "slots": copy.deepcopy(self._reel_slots(reel_id))}

    def slot_detail(self, slot_id: int) -> dict[str, Any] | None:
        s = self._slots.get(slot_id)
        return copy.deepcopy(s) if s else None

    def decided_counts(self, reel_id: int) -> dict[str, int]:
        slots = self._reel_slots(reel_id)
        return {"decided": sum(1 for s in slots if s.get("human_verdict")), "total": len(slots)}

    def reel_cut_dirty(self, reel_id: int) -> bool:
        return bool(self._reels.get(reel_id, {}).get("cut_dirty"))

    def latest_rerender(self, reel_id: int) -> dict[str, Any] | None:
        return None

    def latest_repick(self, slot_id: int) -> dict[str, Any] | None:
        return None

    def curation_batch(self, limit: int = 20) -> list[dict[str, Any]]:
        return copy.deepcopy(self._moments[:limit])

    def list_run_requests(self, limit: int = 10) -> list[dict[str, Any]]:
        return copy.deepcopy(self._runs[:limit])

    def available_references(self) -> list[str]:
        return list(self._references)

    def latest_scheduled_post(self, reel_id: int) -> dict[str, Any] | None:
        sched = self._scheduled.get(reel_id)
        if not sched:
            return None
        return {**sched, "scheduled_at": _dt(sched.get("scheduled_at")),
                "published_at": _dt(sched.get("published_at"))}

    def posted_reels(self) -> list[dict[str, Any]]:
        out = []
        for r in self._reels.values():
            sched = self._scheduled.get(r["id"]) or {}
            if not (r.get("published") or self._pending(r["id"])):
                continue
            out.append({"id": r["id"], "ref": r["ref"], "published": r.get("published", False),
                        "posted": r.get("posted", ""), "is_trial": r.get("is_trial", False),
                        "sched_status": sched.get("status"),
                        "scheduled_at": _dt(sched.get("scheduled_at")),
                        "sched_as_trial": sched.get("as_trial", True),
                        "thumbnail_key": self._first_thumb(r["id"])})
        return sorted(out, key=lambda r: (r["published"], r["id"]))

    def counts(self) -> dict[str, int]:
        return {"reels": len(self._reels),
                "approved": sum(1 for r in self._reels.values() if r["approved"]),
                "unrated_moments": len(self._moments), "rated_moments": 0}

    # -- writes: refused --------------------------------------------------------

    def _refuse(self, *_args, **_kwargs):
        raise PermissionError("the demo data is read-only")

    keep_slot = weak_keep_slot = swap_slot = flag_slot = undo_slot = _refuse
    grade_reel = rate_moment = insert_taste_event = create_run_request = _refuse
    create_scheduled_post = cancel_scheduled_post = _refuse
